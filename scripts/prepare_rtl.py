# 1. Copy the upstream RTL (external/Atari7800_MiSTer/rtl, a pinned
#    submodule) to build/upstream/rtl and apply patches/*.patch there, in
#    name order. The submodule itself is never modified.
# 2. Generate build/generated/atari2600_palette.sv from upstream's NTSC
#    palette (rtl/palettes/NWARM.hex), so synthesis needs no $readmemh.
# 3. Generate rtl/ (gitignored) for the Game Bub framework build, which
#    compiles every file under rtl/. It holds one file, rtl/atari2600_all.sv:
#    `define NO_ARM_MAPPER, then the files of hdl/core.f and hdl/gamebub.f
#    concatenated in list order. One file because the framework reads rtl/ in
#    os.walk order (filesystem-dependent) and Vivado compiles in read order
#    (edalize sets source_mgmt_mode None), while packages, the $unit-scope
#    bss_type enum and the define must come before their users. The framework
#    passes no defines of ours, hence the `define. sim/gamebub compiles this
#    same file.
#
# Re-run after changing a patch, the submodule commit or anything in hdl/;
# it always starts from a fresh copy.
#
# Usage: python3 scripts/prepare_rtl.py

import glob
import os
import shutil
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.join(ROOT, 'external', 'Atari7800_MiSTer')
DST = os.path.join(ROOT, 'build', 'upstream')
STAMP = os.path.join(DST, '.prepared')
FILELISTS = [os.path.join(ROOT, 'hdl', f) for f in ('core.f', 'gamebub.f')]
RTL = os.path.join(ROOT, 'rtl')
GENERATED = os.path.join(ROOT, 'build', 'generated')
RTL_ALL = os.path.join(RTL, 'atari2600_all.sv')

PALETTE_HEADER = '''\
// SPDX-License-Identifier: MIT
// Generated by scripts/prepare_rtl.py from rtl/palettes/NWARM.hex of
// Atari7800_MiSTer (upstream commit %s):
//   Copyright (c) 2019-2026 Jamie Blanks, MIT License (see
//   external/Atari7800_MiSTer/LICENSE). Palette research by Robert Tuccitto.
// Do not edit.
//
// NTSC 2600 palette ("warm"), indexed by the raw TIA colour {chroma, luma}
// (upstream's 256-entry table is indexed by {chroma, luma, 0}).

package atari2600_palette;

	function automatic logic [23:0] ntsc(input logic [6:0] color);
		case (color)
'''


def read_filelist(path):
    with open(path) as f:
        return [l.strip() for l in f if l.strip() and not l.startswith('//')]


def generate_palette(commit):
    with open(os.path.join(DST, 'rtl', 'palettes', 'NWARM.hex')) as f:
        entries = [int(l, 16) for l in f.read().split()]
    if len(entries) != 256:
        raise SystemExit('NWARM.hex: %d entries, want 256' % len(entries))
    os.makedirs(GENERATED, exist_ok=True)
    with open(os.path.join(GENERATED, 'atari2600_palette.sv'), 'w') as f:
        f.write(PALETTE_HEADER % commit)
        for c in range(128):
            f.write("\t\t\t7'h%02x: return 24'h%06x;\n" % (c, entries[2 * c]))
        f.write("\t\t\tdefault: return 24'h000000;\n\t\tendcase\n\tendfunction\n\nendpackage\n")
    print('generated build/generated/atari2600_palette.sv')


def generate_rtl(commit):
    shutil.rmtree(RTL, ignore_errors=True)
    os.makedirs(RTL)
    srcs = [src for filelist in FILELISTS for src in read_filelist(filelist)]
    with open(RTL_ALL, 'w') as out:
        out.write('// Generated by scripts/prepare_rtl.py - do not edit (edit hdl/ or patches/).\n'
                  '// The files of hdl/core.f and hdl/gamebub.f in list order, upstream ones\n'
                  '// from MiSTer-devel/Atari7800_MiSTer %s with patches/ applied.\n'
                  '// Each section keeps its own licence header.\n\n'
                  '`define NO_ARM_MAPPER\n' % commit)
        for src in srcs:
            with open(os.path.join(ROOT, src)) as f:
                text = f.read()
            out.write('\n// ==== begin %s ====\n%s%s// ==== end %s ====\n'
                      % (src, text, '' if text.endswith('\n') else '\n', src))
    print('generated rtl/atari2600_all.sv from', len(srcs), 'files in hdl/core.f, hdl/gamebub.f')


def main():
    if not os.path.isdir(os.path.join(SRC, 'rtl')):
        print('missing %s - run: git submodule update --init' % SRC)
        return 1
    commit = subprocess.run(['git', '-C', SRC, 'rev-parse', 'HEAD'],
                            capture_output=True, text=True).stdout.strip()
    shutil.rmtree(DST, ignore_errors=True)
    shutil.copytree(os.path.join(SRC, 'rtl'), os.path.join(DST, 'rtl'))
    patches = sorted(glob.glob(os.path.join(ROOT, 'patches', '*.patch')))
    for p in patches:
        r = subprocess.run(['patch', '-p1', '--forward', '--batch', '-d', DST, '-i', p],
                           capture_output=True, text=True)
        if r.returncode:
            print('failed to apply %s:\n%s%s' % (os.path.relpath(p, ROOT), r.stdout, r.stderr))
            return 1
        print('applied', os.path.relpath(p, ROOT))
    with open(STAMP, 'w') as f:
        f.write('upstream %s\n' % commit)
        f.writelines('%s\n' % os.path.relpath(p, ROOT) for p in patches)
    print('prepared', os.path.relpath(DST, ROOT), 'from upstream', commit[:12])
    generate_palette(commit)
    generate_rtl(commit)
    return 0


if __name__ == '__main__':
    sys.exit(main())
